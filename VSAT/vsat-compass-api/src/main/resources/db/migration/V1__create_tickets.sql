CREATE TABLE IF NOT EXISTS tickets (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id      BIGINT,
    reporter_user_id BIGINT      NOT NULL,
    message          TEXT        NOT NULL,
    status           VARCHAR(30) NOT NULL,
    resolver_note    TEXT,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now()
);

ALTER TABLE tickets ADD COLUMN IF NOT EXISTS reporter_user_id BIGINT;
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS message TEXT;
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS resolver_note TEXT;
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS created_at TIMESTAMPTZ NOT NULL DEFAULT now();
ALTER TABLE tickets ADD COLUMN IF NOT EXISTS updated_at TIMESTAMPTZ NOT NULL DEFAULT now();

DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'tickets' AND column_name = 'reporter_id'
    ) THEN
        UPDATE tickets
        SET reporter_user_id = reporter_id
        WHERE reporter_user_id IS NULL AND reporter_id IS NOT NULL;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'tickets' AND column_name = 'description'
    ) THEN
        UPDATE tickets
        SET message = description
        WHERE message IS NULL AND description IS NOT NULL;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'tickets' AND column_name = 'resolution_note'
    ) THEN
        UPDATE tickets
        SET resolver_note = resolution_note
        WHERE resolver_note IS NULL AND resolution_note IS NOT NULL;
    END IF;

    IF EXISTS (
        SELECT 1 FROM information_schema.columns
        WHERE table_name = 'tickets' AND column_name = 'status'
          AND data_type = 'USER-DEFINED'
    ) THEN
        ALTER TABLE tickets ALTER COLUMN status DROP DEFAULT;
        ALTER TABLE tickets ALTER COLUMN status TYPE VARCHAR(30)
        USING CASE status::text
            WHEN 'NEW' THEN 'OPEN'
            WHEN 'RESOLVED' THEN 'CLOSED'
            WHEN 'CANCELLED' THEN 'CLOSED'
            ELSE status::text
        END;
    END IF;
END $$;

